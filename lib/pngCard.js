class Canvas {
    constructor(w, h, bg) {
        this.w = w; this.h = h;
        this.buf = Buffer.alloc(w * h * 3);
        this.rect(0, 0, w, h, bg);
    }
    rect(x, y, w, h, [r, g, b]) {
        for (let yy = Math.max(0, y); yy < Math.min(this.h, y + h); yy++) {
            for (let xx = Math.max(0, x); xx < Math.min(this.w, x + w); xx++) {
                const i = (yy * this.w + xx) * 3;
                this.buf[i] = r; this.buf[i + 1] = g; this.buf[i + 2] = b;
            }
        }
    }
    textWidth(s, scale) { return String(s).length * 6 * scale - scale; }
    text(x, y, s, scale, color) {
        let cx = x;
        for (const ch of String(s).toUpperCase()) {
            const rows = FONT[ch] || FONT[' '];
            for (let r = 0; r < 7; r++) for (let c = 0; c < 5; c++) if (rows[r] & (1 << (4 - c))) this.rect(cx + c * scale, y + r * scale, scale, scale, color);
            cx += 6 * scale;
        }
    }
    // PNG: 8-bit RGB, no filtering, one zlib stream.
    png() {
        const raw = Buffer.alloc((this.w * 3 + 1) * this.h);
        for (let y = 0; y < this.h; y++) this.buf.copy(raw, y * (this.w * 3 + 1) + 1, y * this.w * 3, (y + 1) * this.w * 3);
        const chunk = (type, data) => {
            const len = Buffer.alloc(4); len.writeUInt32BE(data.length);
            const td = Buffer.concat([Buffer.from(type), data]);
            const crc = Buffer.alloc(4); crc.writeUInt32BE(crc32(td) >>> 0);
            return Buffer.concat([len, td, crc]);
        };
        const ihdr = Buffer.alloc(13); ihdr.writeUInt32BE(this.w, 0); ihdr.writeUInt32BE(this.h, 4); ihdr[8] = 8; ihdr[9] = 2;
        return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', ihdr), chunk('IDAT', zlib.deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]);
    }
}

const CRC_TABLE = (() => { const t = []; for (let n = 0; n < 256; n++) { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xEDB88320 ^ (c >>> 1) : c >>> 1; t[n] = c >>> 0; } return t; })();
function crc32(buf) { let c = 0xFFFFFFFF; for (let i = 0; i < buf.length; i++) c = CRC_TABLE[(c ^ buf[i]) & 0xFF] ^ (c >>> 8); return c ^ 0xFFFFFFFF; }

module.exports = { Canvas };
