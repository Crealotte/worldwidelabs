// lib/pngCard.js — draws a small picture (bars and text) and encodes it as a PNG, with no libraries:
// a built-in 5x7 pixel font and Node's own zlib. Used for the Steadfast countdown image that can be put
// in a Torn faction announcement (Torn shows images from other sites, like YATA's posters, and a PNG is
// the safest format for that). Only capital letters, digits and a few signs are drawn — anything else is
// shown as a space.

const zlib = require('zlib');

